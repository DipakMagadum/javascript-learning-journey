let productPrice = 1200;

let budget = 1500;

console.log(productPrice > budget); // > Greater than

console.log(productPrice < budget); // < Less than

console.log(productPrice >= budget); // >= Greater than or equal to

console.log(productPrice <= budget); // <= Less than or equal to

console.log(productPrice == budget); // == Equal to

console.log(productPrice != budget); // != Not equal to

